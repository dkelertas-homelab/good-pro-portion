import 'package:flutter/foundation.dart';
import 'package:flutter/services.dart';
import 'package:shared_preferences/shared_preferences.dart';

/// How loud the workout cues are. The app-bar sound button cycles these.
enum SoundLevel {
  on(1.0, 'On'),
  soft(0.3, 'Soft'),
  mute(0.0, 'Mute');

  const SoundLevel(this.volume, this.label);
  final double volume;
  final String label;

  SoundLevel get next =>
      SoundLevel.values[(index + 1) % SoundLevel.values.length];
}

enum Cue { blip, moveStart, restStart }

/// Plays sounds. The real one talks to the Android side (AudioCues.kt); tests
/// use a fake.
abstract class SoundBackend {
  Future<void> load(Map<String, String> assets);
  Future<void> play(String name, double volume);
  Future<void> startMusic(String asset, double volume);
  Future<void> musicVolume(double volume);
  Future<void> pauseMusic();
  Future<void> resumeMusic();
  Future<void> stopMusic();
}

class PlatformSoundBackend implements SoundBackend {
  static const _ch = MethodChannel('space.d11s.niceproportions/audio');

  Future<void> _call(String method, [Object? args]) async {
    try {
      await _ch.invokeMethod<void>(method, args);
    } on MissingPluginException {
      // Not on Android (tests, desktop): stay quiet.
    } on PlatformException catch (e) {
      debugPrint('audio $method failed: ${e.message}');
    }
  }

  @override
  Future<void> load(Map<String, String> assets) => _call('load', assets);
  @override
  Future<void> play(String name, double volume) =>
      _call('play', {'name': name, 'volume': volume});
  @override
  Future<void> startMusic(String asset, double volume) =>
      _call('startMusic', {'asset': asset, 'volume': volume});
  @override
  Future<void> musicVolume(double volume) =>
      _call('musicVolume', {'volume': volume});
  @override
  Future<void> pauseMusic() => _call('pauseMusic');
  @override
  Future<void> resumeMusic() => _call('resumeMusic');
  @override
  Future<void> stopMusic() => _call('stopMusic');
}

/// App-wide sound settings and playback. Settings are saved on the phone.
/// Defaults: cues Soft, music off.
class Sound {
  Sound({SoundBackend? backend}) : backend = backend ?? PlatformSoundBackend();

  static Sound instance = Sound();

  static const _kLevel = 'sound_level';
  static const _kMusic = 'background_music';

  /// All generated by tool/sounds.py.
  static const cueAssets = {
    Cue.blip: 'assets/sounds/blip.wav',
    Cue.moveStart: 'assets/sounds/move_start.wav',
    Cue.restStart: 'assets/sounds/rest_start.wav',
  };
  static const musicAsset = 'assets/sounds/music_loop.wav';

  /// Music sits well under the cues.
  static const musicShare = 0.35;

  final SoundBackend backend;
  final level = ValueNotifier<SoundLevel>(SoundLevel.soft);
  final music = ValueNotifier<bool>(false);
  SharedPreferences? _prefs;
  bool _musicPlaying = false;

  Future<void> init({SharedPreferences? prefs}) async {
    _prefs = prefs ?? await SharedPreferences.getInstance();
    final saved = _prefs!.getString(_kLevel);
    level.value = SoundLevel.values.firstWhere(
      (l) => l.name == saved,
      orElse: () => SoundLevel.soft,
    );
    music.value = _prefs!.getBool(_kMusic) ?? false;
    await backend.load({
      for (final e in cueAssets.entries) e.key.name: e.value,
    });
  }

  Future<void> setLevel(SoundLevel l) async {
    level.value = l;
    await _prefs?.setString(_kLevel, l.name);
    if (_musicPlaying) await backend.musicVolume(l.volume * musicShare);
  }

  Future<void> cycleLevel() => setLevel(level.value.next);

  Future<void> setMusic(bool on) async {
    music.value = on;
    await _prefs?.setBool(_kMusic, on);
  }

  void play(Cue cue) {
    final v = level.value.volume;
    if (v <= 0) return;
    backend.play(cue.name, v);
  }

  /// Workout start: only if the music switch is on.
  void startWorkoutMusic() {
    if (!music.value) return;
    _musicPlaying = true;
    backend.startMusic(musicAsset, level.value.volume * musicShare);
  }

  void pauseWorkoutMusic() {
    if (_musicPlaying) backend.pauseMusic();
  }

  void resumeWorkoutMusic() {
    if (_musicPlaying) backend.resumeMusic();
  }

  void stopWorkoutMusic() {
    if (!_musicPlaying) return;
    _musicPlaying = false;
    backend.stopMusic();
  }
}
